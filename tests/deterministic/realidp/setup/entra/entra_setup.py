def get_tenant_domain(token: str) -> str:
    # Use ENTRA_DOMAIN if already set — avoids requiring Organization.Read.All.
    if domain := os.environ.get("ENTRA_DOMAIN", "").strip():
        return domain
    org = get(token, "/organization")
    domains = org["value"][0]["verifiedDomains"]
    return next((d["name"] for d in domains if d.get("isDefault")), domains[0]["name"])


def _resolve_password(password_env: str) -> str:
    """Read the password from an env var; exit loudly if unset."""
    value = os.environ.get(password_env, "")
    if not value:
        print(f"ERROR: {password_env} is not set — set it before running this script.")
        print("  Passwords are never committed; inject them as env vars or masked CI variables.")
        sys.exit(1)
    return value


def ensure_user(token: str, username: str, password: str, domain: str) -> str:
    """Create a user if absent; return Object ID."""
    upn = f"{username}@{domain}"
    existing = get(token, f"/users?$filter=userPrincipalName eq '{upn}'")
    if existing["value"]:
        print(f"    [user] Already exists: {upn}")
        return existing["value"][0]["id"]
    u = post(token, "/users", {
        "displayName":       username,
        "userPrincipalName": upn,
        "mailNickname":      username,
        "accountEnabled":    True,
        "passwordProfile": {
            "password":                      password,
            "forceChangePasswordNextSignIn": False,
        },
    })
    print(f"    [user] Created: {upn} ({u['id']})")
    return u["id"]


def add_user_to_group(token: str, user_id: str, group_id: str, group_name: str,
                      retries: int = 5, delay: int = 3) -> None:
    """Add user to group; retry on 404 (Entra replication lag); skip if already a member."""
    for attempt in range(retries):
        try:
            post(token, f"/groups/{group_id}/members/$ref", {
                "@odata.id": f"{GRAPH_BASE}/directoryObjects/{user_id}"
            })
            print(f"      [membership] Added to {group_name}")
            return
        except requests.HTTPError as e:
            status = e.response.status_code
            if status == 404 and attempt < retries - 1:
                print(f"      [membership] Group not yet replicated, retrying in {delay}s... ({attempt + 1}/{retries})")
                time.sleep(delay)
            elif status == 400 and "already exist" in e.response.text.lower():
                print(f"      [membership] Already a member of {group_name}")
                return
            else:
                raise
    print(f"      [membership] ERROR: failed to add {user_id} to {group_name} after {retries} attempts")


