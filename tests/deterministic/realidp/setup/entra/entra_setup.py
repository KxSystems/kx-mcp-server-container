def ensure_token_lifetime_policy(token: str, app_object_id: str, app_client_id: str,
                                  lifespan_seconds: int) -> None:
    """Attach a token lifetime policy to the service principal (requires Azure AD P1)."""
    minutes = max(lifespan_seconds // 60, 10)
    hours = minutes // 60
    remaining_mins = minutes % 60
    duration = f"{hours:02d}:{remaining_mins:02d}:00"

    try:
        sp = get(token, f"/servicePrincipals?$filter=appId eq '{app_client_id}'")
        if not sp["value"]:
            print("  [policy] SKIPPED — no service principal found")
            return
        sp_id = sp["value"][0]["id"]

        existing = get(token, f"/servicePrincipals/{sp_id}/tokenLifetimePolicies")
        if existing["value"]:
            print("  [policy] Token lifetime policy already attached")
            return

        policy = post(token, "/policies/tokenLifetimePolicies", {
            "definition": [json.dumps({
                "TokenLifetimePolicy": {"Version": 1, "AccessTokenLifetime": duration}
            })],
            "displayName":           f"kdbai-access-token-{minutes}min",
            "isOrganizationDefault": False,
        })
        post(token, f"/servicePrincipals/{sp_id}/tokenLifetimePolicies/$ref", {
            "@odata.id": f"{GRAPH_BASE}/policies/tokenLifetimePolicies/{policy['id']}"
        })
        print(f"  [policy] Token lifetime set to {duration}")

    except requests.HTTPError as e:
        if e.response.status_code == 403:
            print("  [policy] SKIPPED — requires Azure AD Premium P1 licence")
        else:
            print(f"  [policy] WARNING — failed ({e.response.status_code}): {e.response.text[:200]}")


