def ensure_group(token: str, display_name: str) -> str:
    """Create security group if absent; return its Object ID."""
    existing = get(token, f"/groups?$filter=displayName eq '{display_name}'")
    if existing["value"]:
        print(f"    [group] Already exists: {display_name}")
        return existing["value"][0]["id"]
    g = post(token, "/groups", {
        "displayName":     display_name,
        "mailEnabled":     False,
        "mailNickname":    display_name.replace("-", ""),
        "securityEnabled": True,
        "description":     "kx-mcp-server real-IdP test group",
    })
    print(f"    [group] Created: {display_name} ({g['id']})")
    time.sleep(5)
    return g["id"]


