def ensure_app_registration(token: str, client_id_name: str) -> tuple[dict, str | None]:
    """Create the app registration if absent; configure service principal, API scope,
    access token version, redirect URI, client secret, and groups claim."""
    existing = get(token, f"/applications?$filter=displayName eq '{client_id_name}'")
    if existing["value"]:
        app = existing["value"][0]
        print(f"  [app] Already exists: {client_id_name} ({app['id']})")
    else:
        app = post(token, "/applications", {
            "displayName":            client_id_name,
            "signInAudience":         "AzureADMyOrg",
            "publicClient":           {"redirectUris": ["http://localhost"]},
            "isFallbackPublicClient": True,
        })
        print(f"  [app] Created: {client_id_name} ({app['id']})")
        time.sleep(10)  # Brief delay for propagation before configuring it further

    ensure_service_principal(token, app["appId"])
    configure_api_scope(token, app["id"], app["appId"])
    configure_redirect_uri(token, app["id"], ENTRA_REDIRECT_URI)
    configure_optional_claims(token, app["id"])
    configure_public_client_flow(token, app["id"], _PERSONA_CONFIG["client"]["public_client"])
    secret_value = ensure_client_secret(token, app["id"], ENTRA_SECRET_DISPLAY_NAME)
    return app, secret_value


def ensure_service_principal(token: str, app_client_id: str) -> dict:
    existing = get(token, f"/servicePrincipals?$filter=appId eq '{app_client_id}'")
    if existing["value"]:
        print("  [sp] Service principal already exists")
        return existing["value"][0]
    sp = post(token, "/servicePrincipals", {"appId": app_client_id})
    print(f"  [sp] Service principal created ({sp['id']})")
    return sp


def configure_api_scope(token: str, app_object_id: str, app_client_id: str) -> None:
    """
    Expose api://<client-id>/access so tokens have aud=api://<client-id>.

    Also sets requestedAccessTokenVersion=2, required for FastMCP's AzureProvider
    to validate tokens correctly (equivalent to the manual Manifest →
    api.requestedAccessTokenVersion portal step).
    """
    app = get(token, f"/applications/{app_object_id}")
    expected_uri = f"api://{app_client_id}"
    current_version = (app.get("api") or {}).get("requestedAccessTokenVersion")

    uri_ok = expected_uri in (app.get("identifierUris") or [])
    # Key off the scope's own presence, not the identifierUris side effect — otherwise a partial
    # re-run (URI already committed, scope missing for any reason) mints a fresh UUID every time.
    scope_ok = any(s.get("value") == "access" for s in (app.get("api") or {}).get("oauth2PermissionScopes") or [])
    version_ok = current_version == 2

    if uri_ok and scope_ok and version_ok:
        print(f"  [api] Scope already configured: {expected_uri}")
        print("  [api] Access token version already set to 2")
        return

    body: dict = {
        "identifierUris": [expected_uri],
        "api": {
            "requestedAccessTokenVersion": 2,
        },
    }
    if not scope_ok:
        body["api"]["oauth2PermissionScopes"] = [{
            "id":                      str(uuid.uuid4()),
            "adminConsentDescription": "Access KDB.AI",
            "adminConsentDisplayName": "Access KDB.AI",
            "isEnabled":               True,
            "type":                    "User",
            "value":                   "access",
        }]

    patch(token, f"/applications/{app_object_id}", body)
    print(f"  [api] Exposed API: {expected_uri}/access")
    print("  [api] Access token version set to 2")


def configure_redirect_uri(token: str, app_object_id: str, redirect_uri: str) -> None:
    """
    Add a Web platform redirect URI for the OAuth callback FastMCP's AzureProvider uses.
    Equivalent to the manual Authentication → Add a platform → Web portal step.
    """
    app = get(token, f"/applications/{app_object_id}")
    existing_uris = (app.get("web") or {}).get("redirectUris") or []

    if redirect_uri in existing_uris:
        print(f"  [redirect] Already configured: {redirect_uri}")
        return

    patch(token, f"/applications/{app_object_id}", {
        "web": {
            "redirectUris": existing_uris + [redirect_uri],
        },
    })
    print(f"  [redirect] Added: {redirect_uri}")


def ensure_client_secret(token: str, app_object_id: str, description: str) -> str | None:
    """
    Create a client secret for FastMCP's AzureProvider to use at runtime.

    Graph API only returns the secretText value once, at creation. If a secret with
    this display name already exists, a new one is NOT created (to avoid accumulating
    secrets on every run) and None is returned — the existing .env.entra value, if any,
    should be reused. To rotate, delete the existing secret in the portal first.
    """
    app = get(token, f"/applications/{app_object_id}")
    existing = [c for c in app.get("passwordCredentials", []) if c.get("displayName") == description]
    if existing:
        print(f"  [secret] Already exists: {description} (value not retrievable; reusing .env.entra)")
        return None

    cred = post(token, f"/applications/{app_object_id}/addPassword", {
        "passwordCredential": {"displayName": description}
    })
    print(f"  [secret] Created: {description}")
    return cred["secretText"]


def configure_public_client_flow(token: str, app_object_id: str, enabled: bool) -> None:
    """
    Enable ROPC (resource-owner password) sign-in on the app registration.

    Required for the password-flow token acquisition used by test personas
    (EntraTokenProvider's default `flow: password`) and by the manual ROPC
    curl in the summary output. Only set at app-creation time previously —
    idempotent here so it's also fixed up on an app registration that was
    created manually in the portal (the bootstrap path), where it defaults
    to disabled. Equivalent to the manual Authentication → Settings →
    "Allow public client flows" portal toggle.
    """
    app = get(token, f"/applications/{app_object_id}")
    if app.get("isFallbackPublicClient") == enabled:
        print(f"  [public-client] Already {'enabled' if enabled else 'disabled'}")
        return
    patch(token, f"/applications/{app_object_id}", {"isFallbackPublicClient": enabled})
    print(f"  [public-client] {'Enabled' if enabled else 'Disabled'} (ROPC sign-in)")


def configure_optional_claims(token: str, app_object_id: str) -> None:
    """Emit group Object IDs in access tokens."""
    app = get(token, f"/applications/{app_object_id}")
    groups_claim_present = any(
        c.get("name") == "groups"
        for c in (app.get("optionalClaims") or {}).get("accessToken") or []
    )
    if app.get("groupMembershipClaims") == "SecurityGroup" and groups_claim_present:
        print("  [claims] Groups claim already configured")
        return

    patch(token, f"/applications/{app_object_id}", {
        "groupMembershipClaims": "SecurityGroup",
        "optionalClaims": {
            "accessToken": [{"name": "groups", "essential": False, "additionalProperties": []}],
        },
    })
    print("  [claims] Groups claim configured in access token")


