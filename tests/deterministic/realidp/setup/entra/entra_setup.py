def get_access_token() -> str:
    """Obtain a bearer token using the OAuth2 client credentials flow."""
    missing = [k for k, v in ENTRA_CONFIG.items() if not v]
    if missing:
        for key in missing:
            print(f"ERROR: ENTRA_{key.upper()} environment variable not set.")
        sys.exit(1)

    url = f"https://login.microsoftonline.com/{ENTRA_CONFIG['tenant_id']}/oauth2/v2.0/token"
    resp = requests.post(url, data={
        "grant_type":    "client_credentials",
        "client_id":     ENTRA_CONFIG["client_id"].strip(),
        "client_secret": ENTRA_CONFIG["client_secret"],
        "scope":         "https://graph.microsoft.com/.default",
    })
    if resp.status_code != 200:
        print(f"ERROR: Authentication failed ({resp.status_code}): {resp.text}")
        print("  Check ENTRA_CLIENT_SECRET is the secret Value (not a password),")
        print("  and that the app has the required Application permissions with admin consent.")
        sys.exit(1)
    return resp.json()["access_token"]


def graph_headers(token: str) -> dict:
    return {"Authorization": f"Bearer {token}", "Content-Type": "application/json"}


# ---------------------------------------------------------------------------
# Graph API helpers
# ---------------------------------------------------------------------------


def get(token: str, path: str) -> dict:
    r = requests.get(f"{GRAPH_BASE}{path}", headers=graph_headers(token))
    r.raise_for_status()
    return r.json()


def post(token: str, path: str, body: dict) -> dict:
    r = requests.post(f"{GRAPH_BASE}{path}", headers=graph_headers(token), json=body)
    if not r.ok:
        print(f"  [error] POST {path} → {r.status_code}: {r.text}")
    r.raise_for_status()
    return r.json() if r.content else {}


def patch(token: str, path: str, body: dict) -> None:
    r = requests.patch(f"{GRAPH_BASE}{path}", headers=graph_headers(token), json=body)
    r.raise_for_status()


