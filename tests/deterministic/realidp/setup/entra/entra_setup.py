def _read_existing_env_value(var_name: str) -> str:
    """
    Read a previously-written value for var_name from the existing .env.entra, if present.
    Used to preserve values (e.g. ENTRA_CLIENT_SECRET) across re-runs when this run did
    not regenerate them. Returns "" if the file or the variable doesn't exist yet.
    """
    if not _ENV_OUT.exists():
        return ""
    prefix = f"export {var_name}="
    for line in _ENV_OUT.read_text().splitlines():
        if line.startswith(prefix):
            value = line[len(prefix):].strip()
            # write_env_file always wraps values in double quotes — strip them back
            # off so re-writing this value doesn't double the quoting (or, for a
            # value left blank across successive runs, compound it indefinitely).
            if len(value) >= 2 and value[0] == '"' and value[-1] == '"':
                value = value[1:-1]
            return value
    return ""


def _get_preserved_value(var_name: str) -> str:
    """
    Return the value for var_name, preferring os.environ first (the operator's
    exported value on this run), then falling back to the existing .env.entra
    (a value written by a previous run).

    This ensures that:
    - A fresh first run with exported vars populates the output correctly.
    - A re-run with the same vars sourced from the existing .env.entra preserves them.
    - A re-run where the operator forgets to export a var doesn't blank it out.
    """
    return os.environ.get(var_name, "") or _read_existing_env_value(var_name)


def write_env_file(app_client_id: str, all_groups: dict, domain: str, secret_value: str | None) -> None:
    """Write the provisioned values to envs/.env.entra.

    The script reads inputs from the environment and writes the full live .env.entra.
    It does NOT copy .env.entra.example — that is a first-time-only README step.
    Re-running is safe: inputs are preserved from os.environ first, then the
    existing file (see _get_preserved_value).

    The client secret is only retrievable at creation time — it is written when
    freshly generated and preserved across re-runs from the existing file.
    User passwords are NEVER written; see _get_preserved_value.
    """
    tenant_id = ENTRA_CONFIG["tenant_id"]
    client_id = ENTRA_CONFIG["client_id"]
    app_id_uri = f"api://{app_client_id}"

