"""
entra_setup.py — Provision Microsoft Entra ID resources for the real-IdP harness.
==================================================================================

Uses the ``kdbai-service-mcp-agent`` app registration to configure itself and
provision all supporting resources. The same app registration serves two roles:

  1. During setup: authenticates against the Graph API to provision resources.
     Requires broad Graph permissions (see Prerequisites) which can be removed
     from the app registration once provisioning is complete.

  2. At runtime: the app the MCP container validates tokens against.
     Users authenticate against this app registration to obtain JWTs.

Configures the following on the kdbai-service-mcp-agent app registration:
  - Service Principal     (required for token issuance and sign-in)
  - API Scope             (sets aud claim to api://<client-id>)
  - Access token version  (sets requestedAccessTokenVersion=2, required by FastMCP's AzureProvider)
  - Redirect URI          (Web platform callback used by FastMCP's AzureProvider)
  - Client secret         (auto-generated if absent; written to .env.entra)
  - Groups claim          (emits group Object IDs in access tokens, off by default)
  - Public client flows   (enables ROPC password grant; off by default in Entra,
                           fixed up on every run — not just at creation — so an
                           app registration created manually in the portal is
                           also covered)
  - Token Lifetime Policy (attached to the service principal)

Provisions the following directory resources:
  - Security Groups       (one per group per namespace, prefixed with namespace name)
  - Users                 (with passwords, no forced reset on first sign-in)
  - Group memberships     (as defined in the config)

Output:
  Writes the provisioned values (tenant/client IDs, group Object IDs, domain,
  ENTRA_APP_ID_URI, KX_MCP_AUTH_* inbound-validation vars) to
  ``tests/deterministic/realidp/envs/.env.entra`` in ``export VAR=value`` form —
  the format sourced by ``just test-entra``.

  The script reads *inputs* from the environment (tenant/client/secret + passwords)
  and writes the full live ``.env.entra`` (provisioned outputs + preserved inputs).
  It does NOT copy ``.env.entra.example`` — that is a first-time-only README step.
  Re-running the script is safe: all Graph operations are idempotent and existing
  inputs are preserved from ``os.environ`` first, then the existing file.

  User passwords are NEVER written; they must be injected manually or as masked CI
  variables. The client secret IS written since it is generated by this script and
  only retrievable once, at creation time.

  The output file is gitignored. Do NOT commit it.

Prerequisites
-------------
1. Create the ``kdbai-service-mcp-agent`` App Registration in Entra ID and assign
   the following Microsoft Graph *application* permissions, all admin-consented:
     - Application.ReadWrite.All
     - Group.ReadWrite.All
     - User.ReadWrite.All
     - Policy.ReadWrite.ApplicationConfiguration
     - Policy.Read.All
     - Organization.Read.All

   These permissions are only needed to run this script. They can be removed
   from the app registration once provisioning is complete.

2. Set env vars (do not hardcode secrets). You can source your partially-filled
   .env.entra or export them directly:
     export ENTRA_TENANT_ID="<Directory ID from the app registration Overview>"
     export ENTRA_CLIENT_ID="<Application ID from the app registration Overview>"
     export ENTRA_CLIENT_SECRET="<Secret Value>"
     export ENTRA_PASSWORD_ROOT="<password for root user>"
     export ENTRA_PASSWORD_ALICE="<password for alice user>"
     export ENTRA_PASSWORD_BOB="<password for bob user>"
     # Optional — second tenant for charlie / wrong-issuer persona (test 2.41):
     export ENTRA_PASSWORD_CHARLIE="<password for charlie user>"

3. Optionally set:
     export ENTRA_REDIRECT_URI="http://localhost:8000/auth/callback"

4. Run from the repo root:
     uv run python tests/deterministic/realidp/setup/entra/entra_setup.py

The script is fully idempotent. It can be re-run safely without creating duplicate
resources. Existing resources are detected and skipped.
"""

