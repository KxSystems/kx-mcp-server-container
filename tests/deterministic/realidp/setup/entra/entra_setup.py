def main() -> None:
    print("Authenticating with Microsoft Graph...")
    token = get_access_token()

    domain = get_tenant_domain(token)
    print(f"Tenant domain: {domain}")
    print(f"Tenant ID:     {ENTRA_CONFIG['tenant_id']}\n")

    print("=== App Registration ===")
    app, secret_value = ensure_app_registration(token, _PERSONA_CONFIG["client"]["client_id"])

    # All namespaces share one app registration / service principal, so only one
    # token lifetime policy can ever be attached — set it once, up front, rather
    # than per-namespace (a per-namespace call would silently no-op for every
    # namespace after the first, since ensure_token_lifetime_policy's idempotency
    # check is "does a policy exist", not "does it match this namespace's value").
    # All namespaces currently configure the same lifespan; if that ever diverges,
    # this is the one value that wins.
    lifespan = next(iter(_PERSONA_CONFIG["namespaces"].values()))["token_settings"]["access_token_lifespan_seconds"]
    ensure_token_lifetime_policy(token, app["id"], app["appId"], lifespan)

    all_groups: dict[str, str] = {}
    for ns_name, ns_cfg in _PERSONA_CONFIG["namespaces"].items():
        print(f"\n=== Namespace: {ns_name} ===")

        group_ids: dict[str, str] = {}
        for group_name in ns_cfg["groups"]:
            full_name = f"{ns_name}-{group_name}"
            group_ids[group_name] = ensure_group(token, full_name)
            all_groups[full_name] = group_ids[group_name]

        for user_cfg in ns_cfg["users"]:
            # charlie belongs in the second tenant — skip in the primary tenant when
            # ENTRA_TENANT_ID_RISK is not configured. Scoped via second_tenant so a
            # merely-missing password for any other user fails loudly instead.
            if user_cfg.get("second_tenant") and not os.environ.get("ENTRA_TENANT_ID_RISK"):
                print(
                    f"    [user] Skipping {user_cfg['username']} — "
                    "second-tenant vars not set (ENTRA_TENANT_ID_RISK unset); "
                    "test 2.41 will be skipped at runtime."
                )
                continue
            password = _resolve_password(user_cfg["password_env"])
            uid = ensure_user(token, user_cfg["username"], password, domain)
            for g in user_cfg["groups"]:
                add_user_to_group(token, uid, group_ids[g], f"{ns_name}-{g}")

    write_env_file(app["appId"], all_groups, domain, secret_value)
    print_summary(app, domain)
    print("Done.")


if __name__ == "__main__":
    main()
